const ALL_HEXAGRAMS = [...HEXAGRAM_DATA, ...generateRemainingHexagrams()];

export class HexagramDatabase {
    private static _data: HexagramInfo[] = ALL_HEXAGRAMS;

    static getByIndex(index: number): HexagramInfo {
        return this._data[index] || this._data[0];
    }

    static getByLines(lines: number[]): HexagramInfo | null {
        return this._data.find(h =>
            h.lines.length === lines.length &&
            h.lines.every((l, i) => l === lines[i])
        ) || null;
    }

    static getAll(): HexagramInfo[] {
        return this._data;
    }

    static linesToIndex(lines: number[]): number {
        const found = this.getByLines(lines);
        return found ? found.index : 0;
    }

    static getCount(): number {
        return this._data.length;
    }
}
